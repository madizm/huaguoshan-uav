const assert = require('assert');
const Timeline = require('../frontend/src/features/trajectory-prediction/prediction-timeline');
const base = Date.parse('2026-01-01T00:00:00Z');
const prediction = { base_observed_at: new Date(base).toISOString(), predicted_at: new Date(base + 1000).toISOString(), horizon_seconds: 30,
  points: [5, 10, 15, 20, 25, 30].map(t => ({ eta_seconds: t, longitude: 119 + t / 1000, latitude: 34, height_amsl_m: 100 + t, uncertainty_m: 10 + t })) };
assert.strictEqual(Timeline.subjectKey('airspace_target', 42), 'airspace_target:42');
assert.strictEqual(Timeline.pointHeight({height_amsl_m: 0}), 0);
assert.strictEqual(Timeline.pointHeight({height_amsl_m: null}), 100);
assert.strictEqual(Timeline.pointHeight({}), 100);
let clipped = Timeline.clipPrediction(prediction, base + 12000);
assert.strictEqual(clipped.state, 'valid');
assert.strictEqual(clipped.remainingSeconds, 18);
assert.strictEqual(clipped.points[0].eta_seconds, 12);
assert(Math.abs(clipped.points[0].longitude - 119.012) < 1e-8);
assert.strictEqual(clipped.points[0].height_amsl_m, 112);
assert.strictEqual(clipped.points[0].uncertainty_m, 22);
assert.strictEqual(prediction.points[0].eta_seconds, 5, 'do not mutate original records');
assert.strictEqual(Timeline.clipPrediction(prediction, base + 30000).state, 'expired');
assert.strictEqual(Timeline.clipPrediction(prediction, base + 32000).state, 'stale');
assert.strictEqual(Timeline.clipPrediction(prediction, base).state, 'future');
assert.strictEqual(Timeline.clipPrediction({...prediction, quality: 'insufficient_data'}, base + 2000).state, 'insufficient_data');
assert.strictEqual(Timeline.clipPrediction({...prediction, points: []}, base + 2000).state, 'unknown');
assert.strictEqual(Timeline.clipPrediction({...prediction, base_observed_at: 'bad'}, base + 2000).state, 'invalid');
assert.strictEqual(Timeline.clipPrediction({...prediction, horizon_seconds: 10}, base + 12000).state, 'expired');
assert.strictEqual(Timeline.pickReplayPrediction([prediction], base), null, 'do not show not-yet-generated records');
assert.strictEqual(Timeline.pickReplayPrediction([prediction], base + 12000), prediction);
assert.strictEqual(Timeline.pickReplayPrediction([prediction], base + 30000), null, 'actual horizon replaces hardcoded 130s');
assert.strictEqual(Timeline.pickReplayPrediction([{...prediction, predicted_at: new Date(base + 13000).toISOString()}], base + 12000), null);
const unknownHeight = {...prediction, points: prediction.points.map(p => ({...p, height_amsl_m: null}))};
assert.strictEqual(Timeline.clipPrediction(unknownHeight, base + 12000).points[0].height_amsl_m, null);
const oldLong = {...prediction, horizon_seconds:120, points:[5,60,120].map(eta=>({...prediction.points[0],eta_seconds:eta}))};
const newerShort = {...prediction, base_observed_at:new Date(base+30000).toISOString(),predicted_at:new Date(base+31000).toISOString(),horizon_seconds:10,points:prediction.points.slice(0,2)};
assert.strictEqual(Timeline.pickReplayPrediction([oldLong,newerShort],base+45000),null,'do not resurrect superseded long prediction after latest expires');
const refreshedOldObservation = {...oldLong,predicted_at:new Date(base+40000).toISOString()};
assert.strictEqual(Timeline.clipPrediction(refreshedOldObservation,base+41000).state,'observation_stale','fresh computation cannot conceal stale observation');
assert.strictEqual(Timeline.clipPrediction(refreshedOldObservation,base+41000,{maxPredictionAgeSeconds:null}).state,'valid','history replay has no realtime observation age limit');
console.log('prediction timeline tests passed');
